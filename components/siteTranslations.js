export function translateSiteText(value){
  if(typeof value!=='string'||!value.trim())return value;
  const leading=value.match(/^\s*/)?.[0]||'';
  const trailing=value.match(/\s*$/)?.[0]||'';
  const text=value.trim();
  if(SITE_TRANSLATIONS[text])return `${leading}${SITE_TRANSLATIONS[text]}${trailing}`;
  let match=text.match(/^Rs\.\s*([\d,]+)$/i);
  if(match)return `${leading}${match[1]} روپے${trailing}`;
  match=text.match(/^(\d+) available$/i);
  if(match)return `${leading}${match[1]} دستیاب${trailing}`;
  match=text.match(/^(\d+) units currently available$/i);
  if(match)return `${leading}اس وقت ${match[1]} یونٹس دستیاب ہیں${trailing}`;
  match=text.match(/^Order (.+)$/i);
  if(match){const name=PRODUCT_NAMES[match[1]]||match[1];return `${leading}${name} آرڈر کریں${trailing}`;}
  match=text.match(/^Decrease (.+)$/i);
  if(match){const name=PRODUCT_NAMES[match[1]]||match[1];return `${leading}${name} کی تعداد کم کریں${trailing}`;}
  match=text.match(/^Increase (.+)$/i);
  if(match){const name=PRODUCT_NAMES[match[1]]||match[1];return `${leading}${name} کی تعداد بڑھائیں${trailing}`;}
  match=text.match(/^Add (.+) to cart$/i);
  if(match){const name=PRODUCT_NAMES[match[1]]||match[1];return `${leading}${name} کارٹ میں شامل کریں${trailing}`;}
  match=text.match(/^Ask about (.+) on WhatsApp$/i);
  if(match){const name=PRODUCT_NAMES[match[1]]||match[1];return `${leading}${name} کے بارے میں واٹس ایپ پر پوچھیں${trailing}`;}
  match=text.match(/^Open cart with (\d+) items$/i);
  if(match)return `${leading}${match[1]} اشیاء کے ساتھ کارٹ کھولیں${trailing}`;
  match=text.match(/^(.+) product details$/i);
  if(match){const name=PRODUCT_NAMES[match[1]]||match[1];return `${leading}${name} کی پروڈکٹ تفصیلات${trailing}`;}
  return value;
}
